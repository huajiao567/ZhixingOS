// 安全门控：在调用 LLM 前做关键词前置拦截（省钱 + 快速）
const L2_KEYWORDS = [
  '不想活', '自杀', '结束生命', '伤害自己', '自残', '活着没', '活着真没', '想死',
  '死了算', '轻生', '杀了他', '伤害别人', '报复社会', '不想活了', '了结自己',
];
const L1_KEYWORDS = ['崩溃', '撑不住', '绝望', '抑郁', '焦虑到', '彻底不行', '撑不下去'];

export type RiskLevel = 0 | 1 | 2;

export function preCheckRisk(text: string): RiskLevel {
  const cleaned = text.replace(/[\s，。、！？!?,.\u3000]/g, '');
  if (L2_KEYWORDS.some((k) => cleaned.includes(k))) return 2;
  if (L1_KEYWORDS.some((k) => cleaned.includes(k))) return 1;
  return 0;
}

